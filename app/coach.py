"""Conversation-coach playbook: how to respond to the other person's visible mood."""

CONTEXTS = {
    "casual": "Casual chat",
    "work": "Work / meeting",
    "sales": "Sales / negotiation",
    "date": "Date / personal",
    "support": "Customer support",
}

PLAYBOOK = {
    "happy": dict(
        headline="They're enjoying this",
        read="Open, positive and engaged. Rapport is high — a great moment to deepen the connection.",
        tone="Warm & upbeat",
        pace="Match their energy",
        do=["Mirror their enthusiasm and smile back",
            "Build on what's working — ask them to tell you more",
            "Use the goodwill to raise an important point or ask"],
        avoid=["Abruptly switching to a heavy topic",
               "Overselling or talking over their excitement"],
        say=dict(
            casual=["Ha, I love that — what happened next?", "You've clearly got a story there, go on!"],
            work=["Great, sounds like we're aligned — shall we lock in next steps?",
                  "Love the energy on this. What would make it even better?"],
            sales=["Sounds like this really fits — want to talk about getting started?",
                   "What part are you most excited about?"],
            date=["I'm really enjoying this conversation.", "Okay, you have to tell me more about that."],
            support=["Glad that worked for you! Anything else I can sort out while we're here?",
                     "Happy to hear that — I'll make a note so it stays that way."]),
    ),
    "sad": dict(
        headline="They seem down",
        read="Low energy or hurt. They need to feel heard before they can hear you.",
        tone="Gentle & soft",
        pace="Slow down, leave pauses",
        do=["Acknowledge the feeling out loud before problem-solving",
            "Ask an open, caring question and really listen",
            "Lower your volume and soften your expression"],
        avoid=["Jumping straight to fixes or silver linings",
               "Jokes, rushing, or changing the subject"],
        say=dict(
            casual=["Hey, you seem a bit off today — everything okay?", "That sounds really hard. I'm here."],
            work=["I sense this might be frustrating — how are you feeling about it?",
                  "Let's take a moment. What would help most right now?"],
            sales=["It sounds like this has been a tough problem for you. Tell me more about the impact.",
                   "No pressure today — I'd rather understand what you're dealing with."],
            date=["You went a bit quiet — did I say something, or is something on your mind?",
                  "Thanks for sharing that with me. That means a lot."],
            support=["I'm really sorry you're dealing with this — let's fix it together.",
                     "I completely understand how disappointing that is."]),
    ),
    "angry": dict(
        headline="Tension is rising",
        read="Frustrated or irritated. Defuse first; facts land only once they feel respected.",
        tone="Calm & steady",
        pace="Slower, lower voice",
        do=["Stay calm and keep your voice low and even",
            "Validate the frustration without getting defensive",
            "Summarise their concern back to them, then offer a concrete next step"],
        avoid=["Arguing, interrupting or saying 'calm down'",
               "Blaming, jargon, or 'that's our policy'"],
        say=dict(
            casual=["Okay, I can see that really got to you. What's bothering you most?",
                    "Fair enough — I didn't mean it that way. Let me rephrase."],
            work=["I hear you, and your concern is valid. Let's figure out how to fix it.",
                  "Let me make sure I understand the issue correctly..."],
            sales=["I understand — that's a legitimate concern. Let's address it head-on.",
                   "What would need to change for this to work for you?"],
            date=["I can tell I upset you, and I'm sorry. Can you help me understand?",
                  "I want to get this right — talk to me."],
            support=["You have every right to be frustrated. Here's exactly what I'll do now...",
                     "Thank you for your patience — I'm taking ownership of this."]),
    ),
    "fear": dict(
        headline="They look uneasy",
        read="Anxious, uncertain or overwhelmed. They need safety and clarity, not pressure.",
        tone="Reassuring",
        pace="Slow, simple sentences",
        do=["Reassure them and explain what happens next, step by step",
            "Break big things into small, clear pieces",
            "Give them control: offer choices and time"],
        avoid=["Pressure, deadlines or ultimatums",
               "Information overload or vague answers"],
        say=dict(
            casual=["Hey, no stress — we'll figure it out together.", "Is something worrying you?"],
            work=["Let's go through it one step at a time — you won't be on your own with this.",
                  "What part feels most uncertain? Let's tackle that first."],
            sales=["There's no commitment today — let me walk you through exactly how it works.",
                   "What concerns you most? I'll be completely transparent."],
            date=["We can take things at whatever pace feels right for you.",
                  "You can tell me anything — no judgement."],
            support=["Don't worry — your account is safe and I'll guide you through this.",
                     "Here's exactly what will happen next, and when."]),
    ),
    "disgust": dict(
        headline="Something put them off",
        read="Aversion or disapproval — possibly about the topic, an idea or something you said.",
        tone="Curious & non-defensive",
        pace="Pause and check in",
        do=["Pause and ask what didn't sit right",
            "Show you value their view — let them explain",
            "Be ready to drop or reframe the idea"],
        avoid=["Pushing the same point harder",
               "Taking it personally or getting defensive"],
        say=dict(
            casual=["Ha, not a fan? What's your take?", "Okay, I'm getting the sense that's not your thing."],
            work=["I'm sensing some reservations — what's your honest view?",
                  "What would you change about this approach?"],
            sales=["It seems that part didn't resonate — what matters more to you?",
                   "Let's set that option aside. What would be ideal?"],
            date=["Okay, noted — never mentioning that again!", "Did that come out wrong? Let me try again."],
            support=["I can see that's not what you expected — let me find a better option.",
                     "What would a good outcome look like for you?"]),
    ),
    "surprise": dict(
        headline="That caught their attention",
        read="Unexpected reaction — could be delight or shock. Find out which before moving on.",
        tone="Clear & curious",
        pace="Pause, let it land",
        do=["Pause and give them a moment to process",
            "Check how it landed: good surprise or bad surprise?",
            "Clarify or expand on what just surprised them"],
        avoid=["Rushing on to the next point",
               "Piling on more new information immediately"],
        say=dict(
            casual=["Right?! I couldn't believe it either.", "Didn't see that coming, huh?"],
            work=["I know that's a bit unexpected — how does it sit with you?",
                  "Let me give some context on that."],
            sales=["Surprising, right? Most people react the same way — want to see how it works?",
                   "Is that more or less than you expected?"],
            date=["Haha, I wasn't sure how you'd react to that!", "Too much? Or in a good way?"],
            support=["I know that's not what you expected — let me explain why.",
                     "Does that change things for you? Happy to walk through it."]),
    ),
    "neutral": dict(
        headline="Calm, listening",
        read="Composed and attentive — or politely disengaged. Invite them in to read them better.",
        tone="Friendly & engaging",
        pace="Conversational",
        do=["Ask an open-ended question to draw them in",
            "Share something specific or personal to spark interest",
            "Check understanding and invite their opinion"],
        avoid=["Long monologues", "Yes/no questions that end the thread"],
        say=dict(
            casual=["What's been the best part of your week?", "What do you think about that?"],
            work=["What's your take on this so far?", "Does this match what you were expecting?"],
            sales=["What would success look like for you here?", "How are you handling this today?"],
            date=["What's something you're really into lately?", "What's the story behind that?"],
            support=["Just to make sure I understand — what's the main thing you need today?",
                     "Is this the outcome you were looking for?"]),
    ),
}


def coach(emotion, context="casual"):
    entry = PLAYBOOK.get(emotion, PLAYBOOK["neutral"])
    context = context if context in CONTEXTS else "casual"
    return {
        "emotion": emotion if emotion in PLAYBOOK else "neutral",
        "context": context,
        "headline": entry["headline"],
        "read": entry["read"],
        "tone": entry["tone"],
        "pace": entry["pace"],
        "do": entry["do"],
        "avoid": entry["avoid"],
        "say": entry["say"][context],
    }
